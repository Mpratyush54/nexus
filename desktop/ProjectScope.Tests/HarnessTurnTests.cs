using Nexus.Core;
using Xunit;

namespace Nexus.Core.Tests;

public class HarnessTurnTests
{
    [Theory]
    [InlineData("Tool loaded.")]
    [InlineData("  Tool loaded.\n")]
    [InlineData("Tools loaded.")]
    [InlineData("Tool loaded.\nTool loaded.")]
    [InlineData("Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages.")]
    // Claude Code's ToolSearch result as the raw user message stores it.
    [InlineData("""{"role":"user","content":[{"type":"tool_result","tool_use_id":"toolu_1","content":[{"type":"tool_reference","tool_name":"Monitor"}]},{"type":"text","text":"Tool loaded."}]}""")]
    [InlineData("""[{"type":"tool_result","tool_use_id":"toolu_1","content":"Exit code 0"}]""")]
    [InlineData("""{"message":{"role":"user","content":[{"type":"tool_result","tool_use_id":"t","content":"ok"}]}}""")]
    [InlineData("""{"type":"function_call_output","call_id":"c","output":"done"}""")]
    public void HarnessWrittenTurns(string raw) => Assert.True(HarnessTurn.IsHarnessOnly(raw));

    [Theory]
    [InlineData("")]
    [InlineData("Tool loaded. Now fix the sidebar")]
    [InlineData("why does it say Tool loaded.?")]
    [InlineData("make the hero bigger")]
    [InlineData("""{"role":"user","content":[{"type":"tool_result","tool_use_id":"t","content":"ok"},{"type":"text","text":"also rename it"}]}""")]
    [InlineData("""{"role":"user","content":[{"type":"text","text":"hello"}]}""")]
    [InlineData("""{"role":"user","content":[{"type":"image","source":{}}]}""")]
    [InlineData("{ not json, a person typing a brace")]
    public void PersonWrittenTurns(string raw) => Assert.False(HarnessTurn.IsHarnessOnly(raw));

    [Fact]
    public void HarnessOnlyTurnIsNeverATitle()
    {
        Assert.Equal("", HarnessMessage.RequestText("Tool loaded."));
        Assert.Equal("fix it", HarnessMessage.RequestText("fix it"));
    }

    private const string Summary =
        "This session is being continued from a previous conversation that ran out of context. The summary below covers the earlier portion of the conversation.\n\n" +
        "<system-reminder>\n<tools-used-before-summary>Bash, Edit</tools-used-before-summary>\n</system-reminder>\nSummary:\n1. Primary Request and Intent:\n   - make it faster\n\n" +
        "If you need specific details from before compaction, read the full transcript at: C:\\x.jsonl\n" +
        "Continue the conversation from where it left off without asking the user any further questions. Resume directly — do not acknowledge the summary. Pick up the last task as if the break never happened.\n\n";

    [Theory]
    [InlineData("This session is being continued from a previous conversation that ran out of context. The summary below covers the earlier portion of the conversation. <system-reminder> <tools-used-before-summary>AskUserQuestion, Bash, Edit, Grep, PowerShell, Read, TaskCreate")]
    [InlineData("This session is being continued from a p…")]
    public void CompactionSummaryIsNoTitle(string text)
    {
        Assert.Equal("", HarnessMessage.SkipCompaction(text));
        Assert.Equal("", HarnessMessage.RequestText(text));
        Assert.True(HarnessMessage.IsWrapperLine(text));
    }

    [Fact]
    public void CompactionFallsBackToTheNextRequest()
    {
        Assert.Equal("", HarnessMessage.SkipCompaction(Summary));
        Assert.Equal("", HarnessMessage.SkipCompaction(Summary +
            "The messages after this summary are the most recent messages from before compaction, kept verbatim. The summary was written without seeing them, so something it says has not happened yet may already have happened in them."));
        Assert.Equal("Now rename the sidebar", HarnessMessage.SkipCompaction(Summary + "Now rename the sidebar"));
        Assert.Equal("Now rename the sidebar", HarnessMessage.RequestText(Summary + "Now rename the sidebar"));
    }

    [Fact]
    public void OrdinaryTextIsUntouched()
    {
        const string text = "Explain why this session is being continued from a previous conversation";
        Assert.Equal(text, HarnessMessage.SkipCompaction(text));
        Assert.False(HarnessMessage.IsWrapperLine(text));
    }
}
