// Package diagnostics defines the problem-report schema shared by every
// Nexus client (web portal, desktop app, Go core, CLI) and the server's
// POST /v1/diagnostics endpoint, plus the redaction and fingerprinting the
// server applies to each report.
//
// The package has no dependencies on the server or store so the Go core and
// CLI can import it in phase 2 to build, cap and pre-redact reports with the
// exact rules the server enforces. Clients should redact before sending; the
// server redacts again as defense in depth.
package diagnostics

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"regexp"
	"sort"
	"strings"
	"time"
	"unicode/utf8"
)

// Kinds of report.
const (
	KindCrash      = "crash"       // the process or screen died
	KindError      = "error"       // a handled error the user saw
	KindUserReport = "user_report" // "Report a problem" with a note
)

// Sources that may send reports.
const (
	SourceDesktop = "desktop" // the native Windows app (C#)
	SourceCore    = "core"    // the Go core (nexuscore)
	SourceWeb     = "web"     // the web portal
	SourceCLI     = "cli"     // the nexus CLI
)

// Limits. The server truncates fields past these caps (it does not reject),
// except for the whole body, which is rejected with 413 past MaxBodyBytes.
const (
	MaxBodyBytes      = 256 << 10
	MaxMessageChars   = 2000
	MaxStackChars     = 32 << 10
	MaxLogLines       = 200
	MaxLogLineChars   = 1000
	MaxUserNoteChars  = 4000
	MaxVersionChars   = 64
	MaxOSChars        = 128
	MaxContextKeys    = 16
	MaxContextKeyLen  = 64
	MaxContextValLen  = 256
	maxFutureSkew     = 24 * time.Hour
	maxReportAge      = 30 * 24 * time.Hour
	fingerprintFrames = 3
)

// Report is the wire format of one problem report (POST /v1/diagnostics).
// Unknown fields are ignored so newer clients can add fields without
// breaking older servers.
type Report struct {
	// ReportID is generated by the client (UUID or 8-64 chars of
	// [A-Za-z0-9_-]) so a retried upload is stored once. The server
	// generates one when it is empty.
	ReportID   string            `json:"report_id"`
	Kind       string            `json:"kind"`
	Source     string            `json:"source"`
	AppVersion string            `json:"app_version"`
	OS         string            `json:"os"`
	Message    string            `json:"message"`
	Stack      string            `json:"stack,omitempty"`
	Logs       []string          `json:"logs,omitempty"`
	UserNote   string            `json:"user_note,omitempty"`
	Timestamp  *time.Time        `json:"timestamp,omitempty"`
	Context    map[string]string `json:"context,omitempty"`
}

// ErrInvalid wraps every validation failure.
var ErrInvalid = errors.New("invalid report")

var reportIDPattern = regexp.MustCompile(`^[A-Za-z0-9_-]{8,64}$`)

// ValidKind reports whether k is a known kind.
func ValidKind(k string) bool {
	switch k {
	case KindCrash, KindError, KindUserReport:
		return true
	}
	return false
}

// ValidSource reports whether s is a known source.
func ValidSource(s string) bool {
	switch s {
	case SourceDesktop, SourceCore, SourceWeb, SourceCLI:
		return true
	}
	return false
}

// NewReportID returns a random 32-hex-char report ID.
func NewReportID() string {
	var b [16]byte
	_, _ = rand.Read(b[:])
	return hex.EncodeToString(b[:])
}

// Normalize validates r, applies the size caps, redacts every free-text
// field and fills defaults. now is the server's receive time. It returns an
// error wrapping ErrInvalid when kind, source or report_id is unusable or
// the report carries nothing to look at.
func Normalize(r *Report, now time.Time) error {
	r.Kind = strings.ToLower(strings.TrimSpace(r.Kind))
	r.Source = strings.ToLower(strings.TrimSpace(r.Source))
	if !ValidKind(r.Kind) {
		return errors.Join(ErrInvalid, errors.New("kind must be crash, error or user_report"))
	}
	if !ValidSource(r.Source) {
		return errors.Join(ErrInvalid, errors.New("source must be desktop, core, web or cli"))
	}
	r.ReportID = strings.TrimSpace(r.ReportID)
	if r.ReportID == "" {
		r.ReportID = NewReportID()
	} else if !reportIDPattern.MatchString(r.ReportID) {
		return errors.Join(ErrInvalid, errors.New("report_id must be 8-64 characters of A-Z, a-z, 0-9, _ or -"))
	}

	r.AppVersion = truncate(oneLine(Redact(r.AppVersion)), MaxVersionChars)
	r.OS = truncate(oneLine(Redact(r.OS)), MaxOSChars)
	r.Message = truncate(strings.TrimSpace(Redact(r.Message)), MaxMessageChars)
	r.Stack = truncate(strings.TrimSpace(Redact(r.Stack)), MaxStackChars)
	r.UserNote = truncate(strings.TrimSpace(Redact(r.UserNote)), MaxUserNoteChars)

	// Keep the newest lines: the end of a log is what led to the failure.
	if len(r.Logs) > MaxLogLines {
		r.Logs = r.Logs[len(r.Logs)-MaxLogLines:]
	}
	logs := make([]string, 0, len(r.Logs))
	for _, line := range r.Logs {
		line = truncate(strings.TrimRight(Redact(line), " \t\r\n"), MaxLogLineChars)
		if line != "" {
			logs = append(logs, line)
		}
	}
	r.Logs = logs

	if len(r.Context) > 0 {
		keys := make([]string, 0, len(r.Context))
		for k := range r.Context {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		ctx := make(map[string]string, min(len(keys), MaxContextKeys))
		for _, k := range keys {
			if len(ctx) >= MaxContextKeys {
				break
			}
			ck := truncate(oneLine(k), MaxContextKeyLen)
			if ck == "" {
				continue
			}
			ctx[ck] = truncate(oneLine(Redact(r.Context[k])), MaxContextValLen)
		}
		r.Context = ctx
	} else {
		r.Context = nil
	}

	if r.Message == "" && r.Stack == "" && r.UserNote == "" && len(r.Logs) == 0 {
		return errors.Join(ErrInvalid, errors.New("message, stack, logs or user_note is required"))
	}
	if r.Message == "" {
		r.Message = firstLine(r.Stack)
		if r.Message == "" {
			r.Message = truncate(firstLine(r.UserNote), 200)
		}
	}

	now = now.UTC()
	if r.Timestamp == nil || r.Timestamp.IsZero() || r.Timestamp.After(now.Add(maxFutureSkew)) || r.Timestamp.Before(now.Add(-maxReportAge)) {
		t := now
		r.Timestamp = &t
	} else {
		t := r.Timestamp.UTC()
		r.Timestamp = &t
	}
	return nil
}

func oneLine(s string) string {
	s = strings.Map(func(r rune) rune {
		if r == '\n' || r == '\r' || r == '\t' {
			return ' '
		}
		return r
	}, s)
	return strings.TrimSpace(s)
}

func firstLine(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.IndexAny(s, "\r\n"); i >= 0 {
		s = s[:i]
	}
	return truncate(strings.TrimSpace(s), 300)
}

// truncate cuts s to at most n bytes on a rune boundary and replaces
// invalid UTF-8 so Postgres TEXT accepts it.
func truncate(s string, n int) string {
	if !utf8.ValidString(s) {
		s = strings.ToValidUTF8(s, "�")
	}
	s = strings.ReplaceAll(s, "\x00", "")
	if len(s) <= n {
		return s
	}
	cut := n
	for cut > 0 && !utf8.RuneStart(s[cut]) {
		cut--
	}
	return s[:cut] + "…"
}
