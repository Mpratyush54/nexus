import { stripMentions } from './composer-commands'
// What a person wrote, separated from the wrapper an agent harness put around
// it. Mirrors the desktop app (desktop/windows/Core/HarnessMessage.cs and
// ChatTitles.cs) so a chat reads the same in both places. Anything inside
// code (``` fences or `spans`) is never stripped.

export type Attachment = { name: string; path: string; isImage: boolean }
export type EnvelopeKind = 'subagent' | 'agent-message' | 'task'
export type Envelope = {
  kind: EnvelopeKind
  label: string
  title: string
  body: string
  from: string
  status: string
}
export type ParsedTurn = {
  /** The readable message, '' when nothing in the turn was written by a person. */
  text: string
  attachments: Attachment[]
  /** Ambient context the harness attached (browser page, IDE state). */
  context: string[]
  envelopes: Envelope[]
  /** A compaction summary the harness wrote when context ran out. */
  compaction: string
}

const CODE = /```[\s\S]*?(?:```|$)|`[^`\n]*`/g

function codeRanges(text: string): Array<[number, number]> {
  return [...text.matchAll(CODE)].map((m) => [m.index, m.index + m[0].length])
}
const inCode = (ranges: Array<[number, number]>, at: number) =>
  ranges.some(([start, end]) => at >= start && at < end)

/** Replaces matches that start outside code. */
function replaceOutsideCode(
  text: string,
  pattern: RegExp,
  replace: (match: RegExpExecArray) => string,
): string {
  const ranges = codeRanges(text)
  const flags = pattern.flags.includes('g') ? pattern.flags : pattern.flags + 'g'
  const re = new RegExp(pattern.source, flags)
  let out = ''
  let at = 0
  for (let m = re.exec(text); m; m = re.exec(text)) {
    if (m[0].length === 0) {
      re.lastIndex++
      continue
    }
    if (inCode(ranges, m.index)) continue
    out += text.slice(at, m.index) + replace(m)
    at = m.index + m[0].length
  }
  return out + text.slice(at)
}

function firstOutsideCode(text: string, pattern: RegExp): RegExpExecArray | null {
  const ranges = codeRanges(text)
  const re = new RegExp(pattern.source, pattern.flags.includes('g') ? pattern.flags : pattern.flags + 'g')
  for (let m = re.exec(text); m; m = re.exec(text)) {
    if (!inCode(ranges, m.index)) return m
    if (m[0].length === 0) re.lastIndex++
  }
  return null
}

// Blocks a harness injects into a turn; never something a person wrote.
const HARNESS_TAGS =
  'system-reminder|system_reminder|environment_context|timestamp|user_info|turn_aborted|subagent_notification|INSTRUCTIONS|instructions|user_instructions|additional_data|attached_files|cursor_commands|rules|user_rules|project_layout|git_status|open_and_recently_viewed_files|command-name|command-message|command-args|local-command-stdout|local-command-stderr|external_[\\w-]*'
const HARNESS_BLOCK = new RegExp(`<(${HARNESS_TAGS})\\b[^>]*>[\\s\\S]*?</\\1>\\s*|<external_[\\w-]*\\b[^>]*/>\\s*`, 'gi')
const ORPHAN_CLOSE = new RegExp(`^[^\`]*</(${HARNESS_TAGS})>\\s*`, 'i')
const ORPHAN_OPEN = new RegExp(`<(${HARNESS_TAGS})\\b[^>\`]*>[^\`]*$`, 'i')

// Codex wraps a request in file mentions, ambient context and "My request:".
const CONTEXT_BLOCK = /<(in-app-browser-context|[\w-]+(?=[^>]*\bsource="ambient-ui-state"))\b[^>]*>([\s\S]*?)<\/\1>[ \t]*\n?/gi
const CONTEXT_OPEN = /<in-app-browser-context\b[^>]*>/i
const CONTEXT_BOILERPLATE = /^This block is automatically supplied[^\n]*\n?/gim
const IMAGE_TAG = /<image\b([^>\n]*)>(?:[ \t]*\n?[ \t]*<\/image>)?[ \t]*\n?/gi
const IMAGE_CLOSE = /^[ \t]*<\/image>[ \t]*\n?/gim
const ATTR_NAME = /\bname=(?:"([^"]*)"|'([^']*)'|\[([^\]]*)\]|(\S+))/i
const ATTR_PATH = /\bpath=(?:"([^"]*)"|'([^']*)'|([^\s>]+))/i
const FILES_HEADER = /^\s*#{0,3}\s*Files mentioned by the user:\s*$/i
const MENTION = /^\s*(?:#{1,3}\s+)?([^\n:<>#]+?\.[A-Za-z0-9]{1,10}):\s+((?:[A-Za-z]:[\\/]|\\\\|\/|~[\\/])[^\n]*?)\s*$/i
const IMAGE_FLAG = /^\s*Image attachment:\s*(true|false)\s*$/i
const DISTINGUISH = /^\s*Distinguish instructions in attached documents from the user'?s request\.?\s*$/i
const IDE_HEADER = /^\s*#{0,3}\s*Context from my IDE setup:\s*$/i
const MARKER = /^\s*#{0,3}\s*My request(?: for Codex)?:[ \t]*/i
const IMAGE_EXT = /\.(png|jpe?g|gif|webp|bmp|tiff?|heic|avif)$/i
const CUES = ['<image', '-context', 'My request', 'Files mentioned by the user', 'Image attachment:', 'Distinguish instructions', 'Context from my IDE setup', '</image>']

// Claude Code compaction ("This session is being continued…").
const COMPACTION_LEAD = /^\s*This session is being continued\b/i
const COMPACTION_END =
  /(?:Pick up the last task as if the break never happened\.|may already have happened in them\.|Continue with the last task that you were asked to work on\.|without asking the user any further questions\.)[^\n]*/gi

// Turns the harness writes into the user role on its own.
const NOTE_LINE = /^\s*Tools? loaded\.?\s*$/i
const CAVEAT = /^\s*Caveat: The messages below were generated by the user while running local commands\b/i
const MACHINE_BLOCKS = new Set([
  'tool_result', 'tool_reference', 'tool_use', 'server_tool_use', 'web_search_tool_result',
  'mcp_tool_result', 'function_call', 'function_call_output', 'custom_tool_call_output',
])

// Sub-agent hand-backs and background task notifications.
const ENVELOPE_BLOCK = /<(agent-message|task-notification)\b([^>]*)>([\s\S]*?)(?:<\/\1>|$)/gi
const ENVELOPE_LEAD = /(?:^|\n)[ \t]*Another Claude session sent a message:[ \t]*(?=\s*<agent-message\b)/gi
const ENVELOPE_TRAILER = /(<\/agent-message>)\s*That ["“]?other Claude session["”]?[\s\S]*?(?=\n[ \t]*\n|$)/gi
const HAND_BACK = /^\s*\[Subagent hand-back\][\s\S]*?The report follows:[ \t]*\n?/i
const ANNOTATION = /^\s*(?:\[harness:[^\]]*\][^\n]*|\[Subagent hand-back\][^\n]*)(?:\n|$)/i
const TOOLS_USED = /[ \t]*<tools-used-before-summary\b[^>]*>[\s\S]*?<\/tools-used-before-summary>[ \t]*\n?/gi
const RESUME_TRAILER = /\n[ \t]*agentId:\s*[0-9a-f]{8,}\b[^\n]*(?:\n[ \t]*<usage>[\s\S]*?<\/usage>)?\s*$/i

function dedent(text: string): string {
  const lines = text.split('\n')
  const indents = lines.filter((l) => l.trim()).map((l) => l.length - l.trimStart().length)
  const indent = indents.length ? Math.min(...indents) : 0
  return indent === 0 ? text : lines.map((l) => (l.length >= indent ? l.slice(indent) : l.trimStart())).join('\n')
}

function stripAnnotations(text: string): string {
  let rest = text.replace(/\r\n/g, '\n')
  for (let m = ANNOTATION.exec(rest); m; m = ANNOTATION.exec(rest)) rest = rest.slice(m[0].length)
  return rest.trim()
}

function firstLine(text: string): string {
  for (const raw of text.split('\n')) {
    const heading = /^\s*#{1,6}\s/.test(raw)
    let line = raw.replace(/`|\*\*/g, '').replace(/^\s*(?:#{1,6}\s+|[-*]\s+)/, '').trim()
    if (!line || ANNOTATION.test(line)) continue
    const sentence = !heading ? /^.{12,}?[.!?](?=\s)/.exec(line) : null
    if (sentence) line = sentence[0]
    return line.length <= 100 ? line : line.slice(0, 99).trimEnd() + '…'
  }
  return ''
}

function attr(pattern: RegExp, attrs: string): string {
  const m = pattern.exec(attrs)
  return m ? (m.slice(1).find((v) => v !== undefined) ?? '').trim() : ''
}

function addAttachment(list: Attachment[], name: string, path: string, isImage: boolean) {
  const key = path.replace(/\//g, '\\').replace(/\\$/, '').toLowerCase()
  const existing = key ? list.findIndex((a) => a.path.replace(/\//g, '\\').replace(/\\$/, '').toLowerCase() === key) : -1
  if (existing >= 0) {
    const prior = list[existing]
    list[existing] = { ...prior, name: prior.name || name, isImage: prior.isImage || isImage }
    return
  }
  list.push({ name: name.trim(), path: path.trim(), isImage })
}

function addContext(list: string[], block: string) {
  const text = block.replace(CONTEXT_BOILERPLATE, '').trim()
  if (text) list.push(text)
}

/** Codex request wrapper → request text, attachments and ambient context. */
export function parseRequest(raw: string): { text: string; attachments: Attachment[]; context: string[] } {
  const attachments: Attachment[] = []
  const context: string[] = []
  if (!CUES.some((cue) => raw.toLowerCase().includes(cue.toLowerCase()))) return { text: raw, attachments, context }
  let text = raw.replace(/\r\n/g, '\n')
  text = replaceOutsideCode(text, CONTEXT_BLOCK, (m) => {
    addContext(context, m[2])
    return ''
  })
  const open = firstOutsideCode(text, CONTEXT_OPEN)
  if (open) {
    addContext(context, text.slice(open.index + open[0].length))
    text = text.slice(0, open.index)
  }
  text = replaceOutsideCode(text, IMAGE_TAG, (m) => {
    const path = attr(ATTR_PATH, m[1])
    const name = attr(ATTR_NAME, m[1])
    if (path || name) addAttachment(attachments, name, path, true)
    return ''
  })
  text = replaceOutsideCode(text, IMAGE_CLOSE, () => '')

  const lines = text.split('\n')
  let at = 0
  let head = ''
  let preamble = false
  const nextNonBlank = (from: number) => {
    for (let i = from; i < lines.length; i++) if (lines[i].trim()) return i
    return -1
  }
  const mention = (index: number) => {
    const m = MENTION.exec(lines[index])
    if (!m) return false
    const path = m[2].trim().replace(/^"|"$/g, '')
    let isImage = IMAGE_EXT.test(path) || IMAGE_EXT.test(m[1])
    const next = nextNonBlank(index + 1)
    const flag = next >= 0 ? IMAGE_FLAG.exec(lines[next]) : null
    if (flag) isImage = flag[1].toLowerCase() === 'true'
    addAttachment(attachments, '', path, isImage)
    return true
  }
  while (at < lines.length) {
    const line = lines[at]
    if (!line.trim()) { at++; continue }
    if (FILES_HEADER.test(line)) {
      preamble = true
      at++
      while (at < lines.length) {
        if (!lines[at].trim()) { at++; continue }
        if (mention(at)) { at++; continue }
        if (IMAGE_FLAG.test(lines[at])) { at++; continue }
        break
      }
      continue
    }
    const next = nextNonBlank(at + 1)
    if (MENTION.test(line) && next >= 0 && IMAGE_FLAG.test(lines[next])) {
      preamble = true
      mention(at)
      at = next + 1
      continue
    }
    if (IMAGE_FLAG.test(line) || DISTINGUISH.test(line)) { preamble = true; at++; continue }
    if (IDE_HEADER.test(line)) {
      preamble = true
      let end = lines.length
      for (let i = at + 1, fenced = false; i < lines.length; i++) {
        if (lines[i].trimStart().startsWith('```')) { fenced = !fenced; continue }
        if (!fenced && MARKER.test(lines[i])) { end = i; break }
      }
      addContext(context, lines.slice(at + 1, end).join('\n'))
      at = end
      continue
    }
    const marker = MARKER.exec(line)
    if (marker) {
      preamble = true
      head = line.slice(marker[0].length)
      at++
    }
    break
  }
  if (preamble) {
    const body = lines.slice(at)
    if (head.trim()) body.unshift(head)
    text = body.join('\n')
  }
  return { text: text.trim(), attachments, context }
}

/** Removes harness-injected blocks, keeping formatting and never touching code. */
export function stripHarnessBlocks(raw: string): string {
  if (!raw.includes('<')) return raw.trim()
  let text = replaceOutsideCode(raw, HARNESS_BLOCK, () => '')
  text = text.replace(ORPHAN_CLOSE, '').replace(ORPHAN_OPEN, '')
  return text.trim()
}

/** True when nothing in the turn was typed by a person (tool results, "Tool loaded."). */
export function isHarnessOnly(raw: string): boolean {
  const text = raw.trim()
  if (!text) return false
  if (text[0] === '{' || text[0] === '[') {
    try {
      const verdict = machineBlocks(JSON.parse(text))
      if (verdict !== null) return verdict
    } catch {
      /* not JSON */
    }
  }
  return isNoteText(text)
}

function isNoteText(text: string): boolean {
  if (CAVEAT.test(text)) return true
  const lines = text.split(/\r?\n/).filter((l) => l.trim())
  return lines.length > 0 && lines.every((l) => NOTE_LINE.test(l))
}

function machineBlocks(root: unknown): boolean | null {
  let value = root
  for (let depth = 0; depth < 3 && value && typeof value === 'object' && !Array.isArray(value); depth++) {
    const obj = value as Record<string, unknown>
    if (typeof obj.type === 'string' && MACHINE_BLOCKS.has(obj.type)) return true
    if ('content' in obj) value = obj.content
    else if ('message' in obj) value = obj.message
    else return null
  }
  if (!Array.isArray(value)) return null
  let any = false
  for (const block of value) {
    if (!block || typeof block !== 'object' || typeof (block as { type?: unknown }).type !== 'string') return null
    const { type, text } = block as { type: string; text?: unknown }
    if (MACHINE_BLOCKS.has(type)) { any = true; continue }
    if (type === 'text' && typeof text === 'string' && (!text.trim() || isNoteText(text))) { any = true; continue }
    return false
  }
  return any
}

/** Splits a compaction summary from the request that follows it. */
export function splitCompaction(text: string): { summary: string; rest: string } {
  if (!COMPACTION_LEAD.test(text)) return { summary: '', rest: text }
  const ends = [...text.matchAll(COMPACTION_END)]
  if (!ends.length) return { summary: text.trim(), rest: '' }
  const last = ends[ends.length - 1]
  const cut = last.index + last[0].length
  const rest = text
    .slice(cut)
    .trim()
    .replace(/^The messages after this summary are the most recent messages[^\n]*?(?:in them\.|\n|$)/i, '')
    .trim()
  return { summary: text.slice(0, cut).trim(), rest }
}

/** Sub-agent reports and task notifications in a user turn, and what is left. */
export function extractEnvelopes(raw: string): { envelopes: Envelope[]; rest: string } {
  const envelopes: Envelope[] = []
  if (!/<(agent-message|task-notification)/i.test(raw)) return { envelopes, rest: raw }
  const text = raw.replace(/\r\n/g, '\n').replace(ENVELOPE_LEAD, '\n').replace(ENVELOPE_TRAILER, '$1')
  const rest = replaceOutsideCode(text, ENVELOPE_BLOCK, (m) => {
    envelopes.push(parseEnvelope(m[1], m[2], m[3]))
    return '\n'
  })
  if (!envelopes.length) return { envelopes, rest: raw }
  return { envelopes, rest: rest.replace(/\n{3,}/g, '\n\n').trim() }
}

function parseEnvelope(tag: string, attrs: string, body: string): Envelope {
  if (tag.toLowerCase() === 'task-notification') {
    const field = (name: string) =>
      (new RegExp(`<${name}\\b[^>]*>([\\s\\S]*?)(?:</${name}>|$)`, 'i').exec(body)?.[1] ?? '').trim()
    const summary = field('summary')
    const status = field('status').toLowerCase()
    let result = field('result')
    if (!summary && !result) result = body.replace(/<[^>]+>/g, ' ').trim()
    return {
      kind: 'task',
      label: 'Background task',
      title: summary || `Background task ${status || 'update'}`,
      body: result,
      from: field('task-id'),
      status,
    }
  }
  const from = attr(/\bfrom=(?:"([^"]*)"|'([^']*)'|([^\s>]+))/i, attrs)
  let text = body.replace(/^\n+|\n+$/g, '')
  const report = HAND_BACK.exec(text)
  if (report) text = text.slice(report[0].length)
  const handBack = !!report || text.trimStart().startsWith('[Subagent hand-back]')
  text = stripAnnotations(dedent(text).trim())
  return {
    kind: handBack ? 'subagent' : 'agent-message',
    label: handBack ? 'Sub-agent report' : 'Agent message',
    title: firstLine(text),
    body: text,
    from,
    status: '',
  }
}

/** A sub-agent's result as its parent's tool step shows it: only the report. */
export function cleanToolResult(raw: string): string {
  if (!raw.includes('<tools-used-before-summary') && !raw.includes('[Subagent hand-back]')) return raw
  let text = raw.replace(/\r\n/g, '\n').replace(TOOLS_USED, '')
  const report = HAND_BACK.exec(text)
  if (report) {
    text = text.slice(report[0].length).replace(RESUME_TRAILER, '')
    text = dedent(text.replace(/^\n+|\n+$/g, ''))
  }
  return stripAnnotations(text)
}

/** Everything a chat view needs from one stored turn's text. */
export function parseTurnText(raw: string): ParsedTurn {
  const empty: ParsedTurn = { text: '', attachments: [], context: [], envelopes: [], compaction: '' }
  let text = raw.trim()
  if (!text) return empty
  if (isHarnessOnly(text)) return empty
  const query = /<user_query>([\s\S]*?)<\/user_query>/i.exec(text)
  if (query) text = query[1]
  const { envelopes, rest } = extractEnvelopes(text)
  text = rest
  const request = parseRequest(text)
  text = stripHarnessBlocks(request.text)
  const { summary, rest: afterSummary } = splitCompaction(text)
  text = afterSummary
  if (/^#\s*AGENTS\.md instructions/i.test(text) || /^<(INSTRUCTIONS|environment_context)\b/i.test(text)) text = ''
  if (isHarnessOnly(text)) text = ''
  return { text: text.trim(), attachments: request.attachments, context: request.context, envelopes, compaction: summary }
}

const AGENT_NAMES: Record<string, string> = {
  claude: 'Claude Code',
  'claude-code': 'Claude Code',
  claude_code: 'Claude Code',
  codex: 'Codex',
  cursor: 'Cursor',
  agent: 'Cursor',
  opencode: 'OpenCode',
  gemini: 'Gemini',
  kimi: 'Kimi',
  copilot: 'Copilot',
  antigravity: 'Antigravity',
  agy: 'Antigravity',
  windsurf: 'Windsurf',
}

/** "claude-code" → "Claude Code". */
export function agentName(harness: string | undefined): string {
  const key = (harness ?? '').trim().toLowerCase()
  if (!key) return 'Agent'
  return AGENT_NAMES[key] ?? key[0].toUpperCase() + key.slice(1)
}

/** The composer's harness option for a stored harness name ("claude-code" → "claude"). */
export function composerHarness(harness: string | undefined): string {
  const key = (harness ?? '').trim().toLowerCase()
  if (key.startsWith('claude')) return 'claude'
  if (key === 'agent') return 'cursor'
  return key
}

const PLACEHOLDER = /^(captured\s+\S+\s+(session|snapshot)|untitled chat|new chat|new conversation|session)$/i

/** A human title: the stored one unless it is a placeholder or wrapper, else the first request. */
export function chatTitle(title: string | undefined, preview: string | undefined, harness: string | undefined): string {
  const clean = (value: string | undefined) =>
    stripMentions(parseTurnText(value ?? '').text).replace(/`|\*\*/g, '').replace(/(^|\s)#{1,6}\s+/g, ' ').replace(/\s+/g, ' ').trim()
  const stored = clean(title)
  if (stored && !PLACEHOLDER.test(stored) && !/^This session is being continued/i.test(title ?? '')) {
    return stored.length <= 80 ? stored : stored.slice(0, 79).trimEnd() + '…'
  }
  const fromPreview = clean(preview)
  if (fromPreview) {
    const end = fromPreview.search(/[\n.?!]/)
    const first = end > 12 && end < 90 ? fromPreview.slice(0, end + 1) : fromPreview
    return first.length <= 70 ? first : first.slice(0, 69).trimEnd() + '…'
  }
  return `${agentName(harness)} chat`
}
